"""XXL STRIP MASTER parameter list -> params.json and src/param_ids.h. Append-only once released."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LISTS = {
    "outIn": ["Out", "In"],
    "hpf": ["Off", "30 Hz", "40 Hz", "50 Hz"],
    "lf": ["30", "50", "70", "90"],
    "hf": ["8k", "12k", "16k", "20k"],
    "vuSource": ["Output", "Input", "HF Red"],
}
def knob(key, name, lo, hi, d, region): return {"key": key, "name": name, "min": lo, "max": hi, "default": d, "dynamic_display": True, "region": region}
def opts(key, name, lst, d, region, **kw):
    p = {"key": key, "name": name, "options": LISTS[lst], "default": d, "region": region}; p.update(kw); return p
def meter(key, name): return {"key": key, "name": name, "min": 0.0, "max": 1.0, "default": 0.0, "region": "meters", "readonly": True, "dynamic_display": True}
P = [
    knob("in_gain", "INPUT", -12.0, 12.0, 0.0, "input"),
    opts("hpf", "HPF", "hpf", 0, "input"),
    opts("drive_in", "DRIVE", "outIn", 0, "drive"),
    knob("drive", "DRIVE", 0.0, 10.0, 3.0, "drive"),
    knob("density", "DENSITY", 0.0, 10.0, 5.0, "drive"),
    opts("eq_in", "EQ", "outIn", 0, "eq"),
    knob("lf_gain", "LF GAIN", -9.0, 9.0, 0.0, "eq"),
    opts("lf_freq", "LF FRQ", "lf", 1, "eq"),
    knob("hf_gain", "HF GAIN", -9.0, 9.0, 0.0, "eq"),
    opts("hf_freq", "HF FRQ", "hf", 1, "eq"),
    opts("hfc_in", "HF COMP", "outIn", 0, "hfcomp"),
    knob("hfc_thr", "THRESH", -10.0, 2.0, 0.0, "hfcomp"),
    knob("hfc_xover", "X-OVER", 3000.0, 20000.0, 8000.0, "hfcomp"),
    opts("img_in", "IMAGE", "outIn", 0, "image"),
    knob("width", "WIDTH", -4.0, 4.0, 0.0, "image"),
    knob("space", "SPACE", -4.0, 4.0, 0.0, "image"),
    opts("trafo", "TRANSF", "outIn", 0, "output"),
    knob("out_gain", "OUTPUT", -12.0, 12.0, 0.0, "output"),
    opts("vu_src", "VU SHOWS", "vuSource", 0, "output"),
    meter("vu", "VU"), meter("gr", "HF RED"),
]
def main():
    with open(os.path.join(ROOT, "params.json"), "w") as f:
        json.dump({"name": "XXL STRIP MASTER", "params": [{k: v for k, v in p.items() if k not in ("region", "readonly")} for p in P]}, f, indent=1); f.write("\n")
    with open(os.path.join(ROOT, "src", "param_ids.h"), "w") as f:
        f.write("// Generated by tools/gen_params.py -- do not edit.\n#pragma once\n\nenum {\n")
        for i, p in enumerate(P): f.write("  P_%s = %d,\n" % (p["key"].upper(), i))
        f.write("  P_COUNT = %d\n};\n\nstatic const char* const kParamKeys[P_COUNT] = {%s};\n" % (len(P), ", ".join('"%s"' % p["key"] for p in P)))
        f.write("static const float kParamMin[P_COUNT] = {%s};\n" % ", ".join(repr(float(p.get("min", 0.0))) + "f" for p in P))
        f.write("static const float kParamMax[P_COUNT] = {%s};\n" % ", ".join(repr(float(p["max"] if "max" in p else len(p["options"]) - 1)) + "f" for p in P))
        f.write("static const float kParamDef[P_COUNT] = {%s};\n" % ", ".join(repr(float(p["default"])) + "f" for p in P))
        f.write("static const unsigned char kParamIsOption[P_COUNT] = {%s};\n" % ", ".join("1" if "options" in p else "0" for p in P))
        f.write("static const unsigned char kParamReadOnly[P_COUNT] = {%s};\n" % ", ".join("1" if p.get("readonly") else "0" for p in P))
    print("params.json + src/param_ids.h: %d parameters" % len(P))
if __name__ == "__main__": main()
